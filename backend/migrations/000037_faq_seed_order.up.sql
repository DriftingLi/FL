-- #1079 修正：帮助中心种子条目的**组内顺序**。
--
-- 000036 把 30 条种子全部写成 sort_order = 0，于是组内排序退化成 (id ASC)，而
-- INSERT ... SELECT ... JOIN 的 id 分配顺序**不保证**等于 VALUES 的书写顺序 —— 线上实际落成了
-- 倒序（「怎么注销账号？」排到了「怎么注册学员账号？」前面）。种子的顺序是**产品语义**
-- （先问怎么开始用、再问怎么退出），不能交给数据库的插入顺序决定。
--
-- 做法：
--   - **不改 000036**：迁移是 append-only，已应用的环境不会重跑它；
--   - 按 (分类 code, **问题原文**) 精确定位，而不是按 id —— id 本身就是那个不确定的量；
--   - 管理员改过问题文本的行匹配不上 → **原样保留**，不会被本迁移覆盖（这正是想要的：
--     人工编辑优先于种子）。

