--
-- 为什么是数据赋价而不是给 000001 的 seed INSERT 补列：迁移只追加不改写——跑过 000001 的
-- 存量库不会重跑 seed INSERT，改基线文件对它们无效。付费课只挑一门：「货叉操作技能训练」
-- （course_id = 5，操作方向的实操技能课）——够验证「列表价格 → 积分兑换 → 权益」全链路即可，
-- 真实定价后续由管理端表单（本票同批落地的 points_price 写入通道）逐课设置。
--
-- 只补 NULL 行：管理端已定过价的课不动，重跑也安全（幂等）。

UPDATE course
SET points_price = 100
WHERE course_id = 5
  AND points_price IS NULL;
